import type { Trade } from '../lib/backtest/types';
import { useStore } from '../state/store';
import { fmtMoney, fmtNum, fmtPct, fmtPrice, fmtTime, pnlClass } from '../lib/format';

const REASONS: Record<Trade['exitReason'], string> = {
  signal: 'signal',
  stop_loss: 'stop loss',
  take_profit: 'take profit',
  end_of_data: 'end of data',
};

export function TradesTable({ trades, limit = 400 }: { trades: Trade[]; limit?: number }) {
  const timeZone = useStore((s) => s.timeZone);
  if (trades.length === 0) {
    return <div className="hint">No trades were generated by this configuration.</div>;
  }
  const shown = trades.slice(0, limit);
  return (
    <div>
      <div className="table-wrap" style={{ maxHeight: 300 }}>
        <table className="data-table">
          <thead>
            <tr>
              <th>#</th>
              <th>Side</th>
              <th>Entry time</th>
              <th>Entry</th>
              <th>Exit time</th>
              <th>Exit</th>
              <th>Qty</th>
              <th>P/L</th>
              <th>P/L %</th>
              <th>Bars</th>
              <th>Exit reason</th>
            </tr>
          </thead>
          <tbody>
            {shown.map((t) => (
              <tr key={t.id}>
                <td>{t.id}</td>
                <td className={t.side === 'long' ? 'side-long' : 'side-short'}>{t.side}</td>
                <td>{fmtTime(t.entryTime, { timeZone })}</td>
                <td>{fmtPrice(t.entryPrice)}</td>
                <td>{fmtTime(t.exitTime, { timeZone })}</td>
                <td>{fmtPrice(t.exitPrice)}</td>
                <td>{fmtNum(t.qty, 4)}</td>
                <td className={pnlClass(t.pnl)}>{fmtMoney(t.pnl)}</td>
                <td className={pnlClass(t.pnlPct)}>{fmtPct(t.pnlPct)}</td>
                <td>{t.bars}</td>
                <td className="muted">{REASONS[t.exitReason]}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      {trades.length > limit && (
        <div className="hint mt-2">
          Showing the first {limit} of {trades.length} trades — export the trade list as CSV for the full log.
        </div>
      )}
    </div>
  );
}
