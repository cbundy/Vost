import { useState } from 'react';
import type { IntervalUnit } from '../../../shared/market.ts';
import { INTERVAL_UNITS, MAX_CUSTOM_TIMEFRAMES, validateNewInterval, type PickerEntry } from '../lib/customTimeframes';
import type { DataProvider } from '../lib/providers/http';
import { useStore } from '../state/store';
import { useChartStore } from '../state/chartContext';
import type { Source } from '../../../shared/timeframes.ts';
import { Modal } from './Modal';

/** The "Custom intervals" dialog: add an interval to the timeframe picker and remove saved ones. */
export function IntervalDialog({ provider, entries, source, onClose }: { provider: DataProvider; entries: PickerEntry[]; source: Source; onClose: () => void }) {
  const chartStore = useChartStore();
  const custom = useStore((s) => s.customTimeframes);
  const addCustomTimeframe = useStore((s) => s.addCustomTimeframe);
  const removeCustomTimeframe = useStore((s) => s.removeCustomTimeframe);
  const [text, setText] = useState('2');
  const [unit, setUnit] = useState<IntervalUnit>('h');

  const full = custom.length >= MAX_CUSTOM_TIMEFRAMES;
  const n = text.trim() === '' ? NaN : Number(text);
  const result = validateNewInterval(n, unit, provider, entries.map((e) => e.interval), source);
  const error = full ? `The list is full (${MAX_CUSTOM_TIMEFRAMES} intervals); remove one to add another.` : 'error' in result ? result.error : null;

  const add = () => {
    if (error || !('interval' in result)) return;
    addCustomTimeframe(result.interval);
    chartStore.getState().setTimeframe(result.interval);
    onClose();
  };

  const preview = 'interval' in result ? (result.base ? `${result.interval} - built from ${result.base}` : `${result.interval} - generated by ${provider.name}`) : null;

  return (
    <Modal
      title="Custom intervals"
      onClose={onClose}
      width={420}
      footer={
        <>
          <button onClick={onClose}>Cancel</button>
          <button className="primary" onClick={add} disabled={error != null}>
            Add
          </button>
        </>
      }
    >
      <form
        className="interval-form"
        onSubmit={(e) => {
          e.preventDefault();
          add();
        }}
      >
        <div className="interval-row">
          <input type="number" min={1} step={1} value={text} onChange={(e) => setText(e.target.value)} aria-label="Interval length" autoFocus />
          <select value={unit} onChange={(e) => setUnit(e.target.value as IntervalUnit)} aria-label="Interval unit">
            {INTERVAL_UNITS.map((u) => (
              <option key={u.unit} value={u.unit}>
                {u.label}
              </option>
            ))}
          </select>
        </div>
        {error ? (
          <div className="interval-msg error" role="alert">
            {error}
          </div>
        ) : (
          preview && <div className="interval-msg">{preview}</div>
        )}
      </form>
      <h3 className="interval-list-title">Saved intervals</h3>
      {custom.length === 0 ? (
        <div className="muted-2">None yet.</div>
      ) : (
        <ul className="interval-list">
          {custom.map((iv) => (
            <li key={iv}>
              <span>{iv}</span>
              <button className="ghost" onClick={() => removeCustomTimeframe(iv)} aria-label={`Remove ${iv}`} title={`Remove ${iv}`}>
                ✕
              </button>
            </li>
          ))}
        </ul>
      )}
    </Modal>
  );
}
